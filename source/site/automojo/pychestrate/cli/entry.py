def _is_supported_command(*, noun: str, verb: str) -> bool:
    """
        Return True if ``(noun, verb)`` is one of the M1-wired commands.

        :param noun: First positional after ``pyc``.
        :param verb: Second positional after ``pyc <noun>``.

        :returns: Boolean.
    """
    if (noun, verb) == ("project", "list"):
        rtnval = True
        return rtnval
    if (noun, verb) == ("plugin-api", _PLUGIN_API_CATALOG_VERB):
        rtnval = True
        return rtnval
    if (noun, verb) == ("ext", _EXT_LIST_VERB):
        rtnval = True
        return rtnval
    rtnval = False
    return rtnval


def main(
        *,
        argv: Optional[Sequence[str]],
        stdout=None,
        stderr=None,
        openapi_fetcher: Optional[Callable[[], Dict]] = None,
        request_opener=None,
        profile_loader: Optional[Callable[[Optional[str]], CliProfile]] = None
    ) -> int:
    """
        CLI entry point.

        :param argv: Override argv (mainly for tests). ``None`` defaults
                     to :data:`sys.argv` slicing.
        :param stdout: Output stream. Defaults to :data:`sys.stdout`.
        :param stderr: Diagnostic stream. Defaults to :data:`sys.stderr`.
        :param openapi_fetcher: Test seam replacing the live HTTP fetch.
        :param request_opener: Test seam replacing the live urllib
                               opener.
        :param profile_loader: Test seam replacing
                               :func:`credentials.load_profile`.

        :returns: Process exit code.
    """
    if argv is None:
        argv_list: Sequence[str] = sys.argv[1:]
    else:
        argv_list = list(argv)

    out_stream = stdout if stdout is not None else sys.stdout
    err_stream = stderr if stderr is not None else sys.stderr

    meta_handler = _select_meta_handler(argv=argv_list)
    if meta_handler is not None:
        rtnval = meta_handler(argv=argv_list, stdout=out_stream, stderr=err_stream)
        return rtnval

    parsed_globals, remainder = _split_global_args(argv=argv_list)

    if len(remainder) < 2:
        err_stream.write("usage: pyc <noun> <verb> [args]\n")
        rtnval = exit_codes.EXIT_USAGE_ERROR
        return rtnval

    noun, verb = remainder[0], remainder[1]
    if _is_supported_command(noun=noun, verb=verb) is False:
        err_stream.write(
            "error: '{} {}' is not wired in M1.\n".format(noun, verb)
        )
        err_stream.write(
            "supported: 'project list', "
            "'plugin-api catalog [<entry-name>]', "
            "'ext list'\n"
        )
        rtnval = exit_codes.EXIT_USAGE_ERROR
        return rtnval

    if profile_loader is None:
        profile_loader_callable = lambda name: credentials.load_profile(profile_name=name)
    else:
        profile_loader_callable = profile_loader

    try:
        profile = profile_loader_callable(parsed_globals.get("profile"))
    except Exception as xcpt:  # noqa: BLE001 — purposeful translation
        rtnval = _map_exception_to_exit_code(xcpt=xcpt, stderr=err_stream)
        return rtnval

    profile = _override_server_url(profile=profile, server_url=parsed_globals.get("server_url"))

    if (noun, verb) == ("plugin-api", _PLUGIN_API_CATALOG_VERB):
        entry_name: Optional[str] = None
        if len(remainder) > 2:
            entry_name = remainder[2]
        rtnval = _handle_plugin_api_catalog(
            profile=profile,
            entry_name=entry_name,
            request_opener=request_opener,
            stdout=out_stream,
            stderr=err_stream,
        )
        return rtnval

    if (noun, verb) == ("ext", _EXT_LIST_VERB):
        rtnval = _handle_ext_list(
            profile=profile,
            request_opener=request_opener,
            stdout=out_stream,
            stderr=err_stream,
        )
        return rtnval

    if openapi_fetcher is None:
        openapi_fetcher_callable = _build_default_openapi_fetcher(profile=profile)
    else:
        openapi_fetcher_callable = openapi_fetcher

    rtnval = _handle_project_list(
        profile=profile,
        openapi_fetcher=openapi_fetcher_callable,
        request_opener=request_opener,
        stdout=out_stream,
        stderr=err_stream,
    )
    return rtnval


def _build_default_openapi_fetcher(*, profile: CliProfile) -> Callable[[], Dict]:
    """
        Build a default fetcher that hits ``/api/v1/_meta/openapi.json``
        on the configured server.

        :param profile: Active :class:`CliProfile`.

        :returns: No-arg callable.
    """

    def _fetch() -> Dict:
        operation = RestOperation(
            operation_id="_meta_openapi",
            method="GET",
            path_template="/api/v1/_meta/openapi.json",
        )
        response = transport.execute_request(
            profile=profile,
            operation=operation,
            path_params={},
            query_params={},
            body=None,
            idempotency_key=None,
            timeout_seconds=None,
            opener=None,
        )
        if isinstance(response.body, dict):
            rtnval = response.body
            return rtnval
        rtnval = {}
        return rtnval

    rtnval = _fetch
    return rtnval


if __name__ == "__main__":
    sys.exit(main(argv=None))
