"""
.. module:: cli.entry
    :platform: Darwin, Linux, Unix, Windows
    :synopsis: ``pyc`` entry-point dispatcher.

.. moduleauthor:: Automation Mojo LLC

The entry point handles three classes of invocation:

1. Static metadata commands (``--version``, ``--help``,
   ``<noun> --help``, ``<noun> <verb> --help``) that never touch the
   network.
2. Dynamic OpenAPI-driven commands (``pyc project list``) which load
   the credentials profile, fetch / cache the OpenAPI document, build
   a command tree, render the argparse for the chosen subcommand, and
   execute via the transport.
3. Failure modes returning the documented exit codes.

M1 ships only ``pyc project list`` end-to-end. Other commands are
generated by the parser but not yet wired to per-noun handlers.
"""

